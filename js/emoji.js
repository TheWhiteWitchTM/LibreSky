export function emojiGroups(query) {
  const needle = String(query || '').trim().toLowerCase();
  return Object.entries(EMOJI).map(([name, list]) => {
    const rows = list.filter(([char, words]) => !needle || char === needle || words.includes(needle) || name.toLowerCase().includes(needle));
    return [name, rows];
  }).filter(([, rows]) => rows.length);
}

export function flagEmoji(query) {
  return emojiGroups(query).find(([name]) => name === 'Flags')?.[1] || [];
}
